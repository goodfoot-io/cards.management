/**
 * Configuration options for the CardsClient.
 *
 * This is SDK-specific configuration, not an API request type.
 */
export interface CardsClientOptions {
  /** Base URL of the Cards V2 server API (including scheme and host). */
  baseUrl: string;
  /** Access token for authentication (if required by the server). */
  accessToken?: string;
  /** Workspace path for scoping API requests. */
  workspacePath?: string;
  /**
   * Whether to retry network failures with exponential backoff.
   * Defaults to `true`. When `false`, network errors throw immediately as
   * {@link NetworkError} — useful for short-lived callers that have their own
   * recovery path (e.g. file watchers, manual refresh) and shouldn't block
   * forever on an unreachable server.
   */
  retryOnNetworkError?: boolean;
  /**
   * Per-request fetch timeout in milliseconds.
   *
   * Each individual HTTP request is aborted after this duration. Defaults to
   * 10 000 (10 s). Set a shorter value when the caller expects the server to
   * respond promptly — e.g. in tests, or when {@link retryOnNetworkError} is
   * `false` and there is no value in waiting long for a single attempt.
   *
   * The timeout doubles on each consecutive network failure (capped at this
   * same value, so it never exceeds it) and resets on the first successful
   * response, mirroring the existing backoff strategy for the retry delay
   * itself.
   */
  requestTimeoutMs?: number;
  /**
   * Maximum number of attempts for a retried (idempotent) request, counting
   * the initial attempt. Defaults to 10 — a generous finite bound so callers
   * never retry forever against an unreachable server. Exhaustion surfaces as
   * {@link RetryExhaustedError}. Invalid values (non-finite, less than 1) fall
   * back to the default — fail closed to the safe bound.
   */
  maxAttempts?: number;
  /**
   * AbortSignal that cancels this client's requests and stops further retries.
   *
   * Checked before each attempt and between backoff sleeps: when it aborts,
   * in-flight fetches are aborted and no further attempt is scheduled — the
   * pending request rejects with {@link RequestCancelledError} immediately.
   */
  signal?: AbortSignal;
}

// ============================================================================
// SDK Convenience Types
// ============================================================================

/**
 * Options for filtering cards when listing.
 *
 * This is a convenience type for the SDK - the actual API request includes
 * workspacePath from CardsClientOptions automatically.
 */
export interface ListCardsOptions {
  /** Filter by card status. */
  status?: CardStatus;
  /** Filter by tag names. */
  tags?: string[];
  /** Search query string (server-side). */
  search?: string;
  /** Maximum number of results to return. */
  limit?: number;
  /** Offset for pagination. */
  offset?: number;
}

/**
 * Options for fetching timeline entries.
 *
 * This is a convenience type matching TimelineRequest from protocol.
 */
export interface TimelineOptions {
  /** Fetch entries before this cursor. */
  before?: string;
  /** Maximum number of entries to return. */
  limit?: number;
}

// ============================================================================
// SDK Input Types (User-facing, without infrastructure fields)
// ============================================================================

/**
 * Data required to create a new card (SDK input).
 *
 * This is the user-facing type for card creation. The SDK automatically adds
 * workspacePath from CardsClientOptions before sending to the API.
 *
 * @see CreateCardRequest for the full wire-level type including workspacePath
 */
export interface CardCreateData {
  /** Correlation UUID for durable outcome lookup; generated by the client when omitted. */
  creationRequestId?: string;
  /** Title of the card. */
  title: string;
  /** Optional tags for categorization and search. */
  tags?: string[];
  /** Optional environment name for action execution. */
  environment?: string;
  /** Optional gate requirements for the card. */
  gates?: {
    planRequired?: boolean;
    mergeRequestRequired?: boolean;
  };
  /** Outgoing relations to other cards. */
  relations?: CardRelation[];
}

/**
 * Data for updating an existing card (SDK input).
 *
 * @see UpdateCardRequest for the canonical wire-level type
 */
export interface CardUpdateData {
  /** New title for the card. */
  title?: string;
  /** New status for the card. */
  status?: CardStatus;
  /** New tags for the card. */
  tags?: string[];
  /** Whether the card is pinned. */
  isPinned?: boolean;
  /** Display order for sorting within status. */
  order?: number;
  /** Partial gate updates (e.g. toggling planRequired or mergeRequestRequired). */
  gates?: Partial<CardGates>;
  /** Updated relations array. undefined = no change; [] = clear all. */
  relations?: CardRelation[];
  /** Git commit author for the update (e.g. 'system <system@cards.local>'). */
  author?: string;
}

// ============================================================================
// Response Types (SDK-specific aliases)
// ============================================================================

/**
 * A comment on a card (SDK response type).
 *
 * This extends the protocol Comment type for SDK contexts.
 */
export interface Comment extends ProtocolComment {
  /** ID of the parent card (SDK convenience field). */
  cardId?: string;
}

/**
 * Response from approving a gate.
 *
 * This is an SDK-specific response type. The actual API returns the updated card.
 */
export interface GateApprovalResponse {
  /** ID of the card the gate belongs to. */
  cardId: string;
  /** Name of the gate that was approved. */
  gateName: 'plan' | 'mergeRequest';
  /** Whether the gate was successfully approved. */
  approved: boolean;
  /** ISO 8601 timestamp when the gate was approved. */
  approvedAt: string;
}

/**
 * Information about a commit associated with a card.
 */
export interface CommitInfo {
  /** Git commit SHA. */
  sha: string;
  /** ISO 8601 timestamp when the commit was added. */
  createdAt: string;
}
